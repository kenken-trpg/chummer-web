export function translate(
  locale: Locale,
  key: MsgKey,
  vars?: Record<string, string | number>,
): string {
  const template = (MESSAGES[locale] ?? MESSAGES.ja)[key] ?? key;
  return vars ? formatMessage(template, vars) : template;
}
